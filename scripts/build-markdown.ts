#!/usr/bin/env bun

// Writes hooks/vendor/markdown.js, the Markdown parser the mod links with,
// from scripts/markdown-entry.ts and the parser packages bun.lock pins. A
// mod loads only its own files, so the parser ships as this one generated
// file. scripts/build-markdown.spec.ts fails when the committed file differs
// from a fresh build, so a dependency bump comes with its rebuilt file.
//
// Usage: bun scripts/build-markdown.ts [--check]
// --check writes nothing and exits 1 when the committed file is stale.
import { join } from "node:path";
import { parseArgs } from "node:util";

const ROOT = join(import.meta.dir, "..");

export const OUTPUT_PATH = "hooks/vendor/markdown.js";

const BANNER = [
  "// Generated by scripts/build-markdown.ts from scripts/markdown-entry.ts.",
  "// Do not edit: run `bun run build:markdown`.",
  "// @ts-nocheck",
  "/* eslint-disable */",
  "",
].join("\n");

/**
 * Bundles the parser for the mod's environment, which has no DOM and no
 * Node: the node target picks the entity decoder that needs no `document`,
 * and NODE_ENV=production picks micromark's builds without the `debug`
 * logger, whose CommonJS would leave a `node:module` import behind.
 */
export async function buildMarkdown(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(ROOT, "scripts/markdown-entry.ts")],
    target: "node",
    format: "esm",
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    minify: true,
  });
  const [output] = result.outputs;
  if (!result.success || output === undefined) {
    throw new AggregateError(result.logs, "bun build failed");
  }

  return BANNER + (await output.text());
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { check: { type: "boolean" } } });
  const built = await buildMarkdown();
  const path = join(ROOT, OUTPUT_PATH);

  if (values.check) {
    const committed = await Bun.file(path)
      .text()
      .catch(() => "");
    if (committed !== built) {
      console.error(
        `${OUTPUT_PATH} is stale. Fix: run \`bun run build:markdown\` and commit the result.`,
      );
      process.exit(1);
    }
  } else {
    await Bun.write(path, built);
    console.log(`wrote ${OUTPUT_PATH}`);
  }
}
